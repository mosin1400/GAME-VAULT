export type ParamType =
  | "string"
  | "number"
  | "boolean"
  | "select"
  | "json"
  | "code"
  | "textarea";

export type ParamDef = {
  name: string;
  label: string;
  type: ParamType;
  default?: unknown;
  options?: { value: string; label: string }[];
  placeholder?: string;
  description?: string;
};

export type NodeDef = {
  type: string;
  name: string;
  category: string;
  icon: string;
  color: string;
  description: string;
  inputs: number; // 0 برای تریگرها
  outputs: string[]; // نام هندل‌های خروجی
  params: ParamDef[];
  trigger?: boolean;
  credentialType?: string;
  handler: string; // نام هندلر اجرایی در سمت سرور
  meta?: Record<string, unknown>;
};

