export const NODE_CATALOG: NodeDef[] = [
  ...CORE_NODES,
  ...INTEGRATIONS.flatMap(expandIntegration),
];

export const NODE_MAP: Record<string, NodeDef> = Object.fromEntries(
  NODE_CATALOG.map((n) => [n.type, n]),
);

export const INTEGRATION_COUNT = INTEGRATIONS.length;
export const NODE_COUNT = NODE_CATALOG.length;

export function getNodeDef(type: string): NodeDef {
  return (
    NODE_MAP[type] ?? {
      type,
      name: type,
      category: "misc",
      icon: "❔",
      color: "#64748b",
      description: "نود ناشناخته",
      inputs: 1,
      outputs: ["main"],
      params: [],
      handler: "noop",
    }
  );
}

/** مقادیر پیش‌فرض پارامترهای یک نود */
export function defaultParams(type: string): Record<string, unknown> {
  const def = getNodeDef(type);
  const out: Record<string, unknown> = {};
  for (const p of def.params) if (p.default !== undefined) out[p.name] = p.default;
  return out;
}

